/* =====================================================================
   ЭНЦИКЛОПЕДИЯ — разделы и карточки.

   Как добавить карточку: допишите объект в ENTRIES.
     id      — латиница, цифры и дефисы, уникальный на всю энциклопедию.
               Из него собирается ссылка: /encyclopedia/flora#vkusnika
     section — раздел: characters | locations | flora | fauna | items
     name    — название
     kind    — короткая подпись над названием («ягода», «зелье»), можно не писать
     text    — описание. Новый абзац — пустая строка (\n\n)
     fact    — «Интересный факт», показывается отдельной плашкой
     image   — картинка: положите файл в public/encyclopedia/ и напишите
               "/encyclopedia/vkusnika.webp". Без картинки рисуется заглушка
     map     — id места в src/data/world.ts: появится кнопка «Показать на карте»,
               а на карте у этого места — «Читать в энциклопедии»
   ===================================================================== */

export type SectionId = "characters" | "locations" | "flora" | "fauna" | "items";

export interface Section {
  id: SectionId;
  name: string;
  /** одна строка на плашке раздела */
  lead: string;
  /** «3 персонажа»: формы для 1, 2–4, 5+ */
  forms: [string, string, string];
}

export interface Entry {
  id: string;
  section: SectionId;
  name: string;
  kind?: string;
  text: string;
  fact?: string;
  image?: string;
  map?: string;
}

